
from datetime import datetime
from typing import Optional

from pydantic import BaseModel, ConfigDict


# ============================================================
# CREATE STUDY PLAN ITEM
# ============================================================

class StudyPlanItemCreate(BaseModel):
    plan_id: int
    topic_id: int
    scheduled_date: datetime
    duration_minutes: int
    priority: Optional[int] = None
    status: str = "pending"

    # Optional session details
    learning_objective: Optional[str] = None
    study_activity: Optional[str] = None
    resources: Optional[list[dict]] = None
    expected_outcome: Optional[str] = None
    session_type: Optional[str] = None
    reason: Optional[str] = None
    score: Optional[float] = None
    learning_status: Optional[str] = None


# ============================================================
# STUDY PLAN ITEM RESPONSE
# ============================================================

class StudyPlanItemResponse(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    item_id: int
    plan_id: int
    topic_id: int
    scheduled_date: datetime
    duration_minutes: int
    priority: Optional[int] = None
    status: str

    # Additional details generated by Study Plan Agent
    learning_objective: Optional[str] = None
    study_activity: Optional[str] = None
    resources: Optional[list[dict]] = None
    expected_outcome: Optional[str] = None
    session_type: Optional[str] = None
    reason: Optional[str] = None
    score: Optional[float] = None
    learning_status: Optional[str] = None


# ============================================================
# UPDATE STUDY PLAN ITEM STATUS
# ============================================================

class StudyPlanItemStatusUpdate(BaseModel):
    status: str
